export function buildJobDocs(now = new Date()) {
  const day = 24 * 60 * 60 * 1000;
  return JOB_SEEDS.map((s) => {
    const requirements = [
      ...s.mandatory.map((skill) => ({ skill, importance: 'mandatory' })),
      ...s.preferred.map((skill) => ({ skill, importance: 'preferred' })),
    ];
    const description = [
      s.intro,
      '',
      'What you will do',
      `- Build and maintain features as part of the ${s.roleCategory.toLowerCase()} team`,
      '- Review code, write documentation and collaborate with product and design',
      '',
      'Requirements',
      ...s.mandatory.map((skill) => `- Hands-on experience with ${skill}`),
      '',
      'Nice to have',
      ...s.preferred.map((skill) => `- ${skill}`),
    ].join('\n');
    return {
      title: s.title,
      company: s.company,
      location: s.location,
      workMode: s.workMode,
      experienceLevel: s.experienceLevel,
      employmentType: s.employmentType || 'full-time',
      roleCategory: s.roleCategory,
      description,
      requirements,
      salary: { min: s.salary[0], max: s.salary[1], currency: 'INR' },
      url: `https://careers.example.com/${s.company.toLowerCase().replace(/[^a-z0-9]+/g, '-')}/${s.title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
      source: 'Prepstack partner (demo)',
      postedAt: new Date(now - s.postedDaysAgo * day),
      closingDate: s.closesInDays === null ? undefined : new Date(now.getTime() + s.closesInDays * day),
      lastVerifiedAt: new Date(now - s.verifiedDaysAgo * day),
      status: s.status || 'open',
    };
  });
}
